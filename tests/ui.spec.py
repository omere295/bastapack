"""End-to-end walk-through of the app in demo mode. Run: python3 tests/ui.spec.py http://localhost:8765/"""
import sys, re
from playwright.sync_api import sync_playwright

BASE = sys.argv[1] if len(sys.argv) > 1 else "http://localhost:8765/"
errors = []
def check(cond, msg):
    print(("PASS " if cond else "FAIL ") + msg)
    if not cond: errors.append(msg)

with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(viewport={"width": 820, "height": 1180}, accept_downloads=True)
    pg.on("pageerror", lambda e: errors.append("JS error: " + str(e)))
    pg.goto(BASE + "?demo")
    pg.fill("#lu", "admin"); pg.fill("#lp", "wrong"); pg.click("button[type=submit]")
    check("שגויים" in pg.inner_text(".err"), "wrong password is refused")
    pg.fill("#lp", "9999"); pg.click("button[type=submit]")
    pg.wait_for_selector(".big.private")
    pg.click(".big.private")
    days = pg.locator(".dayhead .lbl").all_inner_texts()
    check(days[0].startswith("היסטוריה") and days[1].startswith("באיחור"), "history on top, then overdue: " + " | ".join(d.replace("\n", " ") for d in days[:2]))
    card = pg.locator("section.day:not(.overdue) .card").first
    cid = card.get_attribute("id")
    card.locator(".packbox").click()
    pg.wait_for_timeout(200)
    check("חסר אישור משקל" in pg.inner_text("#" + cid + " .msg"), "packing blocked until weights are in")
    check(pg.locator("#" + cid + " .qty").count() > 0, "website quantity shown large")
    for i in range(pg.locator("#" + cid + " .winput").count()):
        inp = pg.locator("#" + cid + " .winput").first
        inp.fill("0.45" if i < 2 else "2"); inp.press("Enter"); pg.wait_for_timeout(150)
    check("כל המשקלים הוזנו" in pg.inner_text("#" + cid + " .msg"), "all weights confirmed message")
    pg.locator("#" + cid + " .packbox").click(); pg.wait_for_timeout(400)
    check(pg.locator("#" + cid + " .packbox").get_attribute("aria-pressed") == "true", "order packed")
    opened = [c.get_attribute("id") for c in pg.locator(".card.open").all()]
    check(len(opened) == 1 and opened[0] != cid, "next order opened automatically: " + str(opened))
    check("הפרש" in pg.inner_text("#" + cid), "price difference chip on packed order")
    pg.locator("#" + cid + " .packbox").click()
    check("לבטל את האריזה" in pg.inner_text(".modal h3"), "unpack asks for confirmation")
    pg.click("#m-ok"); pg.wait_for_timeout(300)
    check(pg.locator("#" + cid + " .packbox").get_attribute("aria-pressed") == "false", "order unpacked")
    # edit: add product
    pg.locator("#" + cid + " .info").click()
    pg.locator("#" + cid + " button:has-text('עריכה')").click()
    pg.locator("#" + cid + " select[data-addp]").select_option(label="גיוזה עוף")
    pg.locator("#" + cid + " input[data-adda]").fill("1")
    pg.locator("#" + cid + " button:has-text('הוספה')").click(); pg.wait_for_timeout(300)
    check(pg.locator("#" + cid + " .iname").count() == 4, "product added while packing")
    # manual private order
    pg.click("text=+ הזמנה חדשה")
    pg.fill("#f-name", "בדיקה ידנית"); pg.fill("#f-phone", "050-1234567"); pg.fill("#f-street", "הרצל"); pg.fill("#f-building", "5")
    check("סשימי טונה אדומה · 102" not in pg.locator("#r-p-0 option").all_inner_texts(), "private order offers website products only")
    pg.select_option("#r-p-0", label="סשימי טונה"); pg.fill("#r-a-0", "0.3")
    pg.click(".modal button:has-text('יצירת הזמנה')"); pg.wait_for_timeout(400)
    check(pg.locator("text=בדיקה ידנית").count() > 0, "manual private order created")
    # bulk + CSV (both sections)
    pg.click("text=בחירה מרובה"); pg.click("text=בחירת כל הפרטיות")
    pg.click(".seg button:has-text('עסקי')"); pg.click("text=בחירת כל העסקיות")
    check("פרטיות" in pg.inner_text(".bulk .grow"), "bulk selection across sections: " + pg.inner_text(".bulk .grow"))
    pg.click(".bulk button:has-text('ייצוא CSV')")
    with pg.expect_download() as dl:
        pg.click(".modal button:has-text('ייצוא')")
    text = open(dl.value.path(), encoding="utf-8-sig").read().replace("\r", "")
    lines = text.split("\n")
    blanks = [i for i, l in enumerate(lines) if l == ""]
    check(len(blanks) >= 2 and blanks[1] == blanks[0] + 1 and lines[blanks[1] + 1].startswith("מספר הזמנה"), "CSV: Private, two empty lines, Business header")
    pg.click("text=סיום בחירה")
    # business: pickup toggle + fire modal
    bcard = pg.locator(".card").first; bid = bcard.get_attribute("id")
    bcard.locator(".info").click()
    pg.locator("#" + bid + " .toggle").click(); pg.wait_for_timeout(300)
    check(pg.locator("#" + bid + " .chip.pick").count() == 1, "business order marked self-pickup")
    pg.locator("#" + bid + " button:has-text('FIRE')").click()
    check(pg.locator("#m-title").inner_text().startswith("הפקת"), "FIRE opens the delivery-note dialog")
    check(pg.locator(".modal [data-act='m-fire']").is_disabled(), "FIRE is blocked until the order is packed")
    pg.click(".modal button:has-text('ביטול')")
    # delete + trash + restore
    pg.locator("#" + bid + " button:has-text('מחיקה')").click(); pg.click("#m-ok"); pg.wait_for_timeout(300)
    check(pg.locator("#" + bid).count() == 0, "deleted order disappears")
    pg.click(".brand"); pg.click("text=סל מחזור")
    pg.click("text=שחזור"); pg.wait_for_timeout(300)
    check("ריק" in pg.inner_text("main"), "order restored from trash")
    pg.click(".brand"); pg.click("text=יומן פעולות"); pg.wait_for_timeout(300)
    check(pg.locator("table.t tbody tr").count() >= 6, "activity log shows actions")
    pg.click(".brand"); pg.click("text=הגדרות")
    check(pg.locator("text=לקוחות עסקיים").count() > 0, "settings page opens")
    pg.fill("#cl-search", "סושי"); pg.wait_for_timeout(200)
    check(pg.locator("tr:has-text('סושי צפון')").count() == 1 and pg.locator("tr:has-text('ביסטרו')").count() == 0, "client search filters the list")
    check(pg.input_value("#cl-search") == "סושי", "search box keeps what was typed")
    pg.click("text=סנכרון מוצרים ממורנינג"); pg.wait_for_timeout(300)
    check("סונכרנו 6 מוצרים" in pg.inner_text("body"), "morning products sync")
    row = pg.locator("tr:has-text('פילה לברק')").first
    row.locator("button:has-text('יחידה')").click(); pg.wait_for_timeout(300)
    check(pg.locator("tr:has-text('פילה לברק')").first.locator("button:has-text('יחידה')").get_attribute("aria-pressed") == "true", "business product unit can be switched")
    pg.locator("tr:has-text('פילה לברק')").first.locator("button:has-text('ק״ג')").click(); pg.wait_for_timeout(300)
    pg.locator("tr:has-text('סושי צפון') button").click(); pg.wait_for_timeout(200)
    labels = pg.locator(".pricegrid label").all_inner_texts()
    check(any("סשימי סלמון · 103" in l for l in labels) and not any("סשימי סלמון נורווגי" in l for l in labels), "client price list shows morning products only")
    pg.click(".modal button:has-text('ביטול')")
    pg.click("text=כתובת אחרת"); pg.wait_for_timeout(200)
    pg.fill("#end-addr", "הרצל 10, ראשון לציון"); pg.click("text=שמירה"); pg.wait_for_timeout(300)
    check(pg.input_value("#end-addr") == "הרצל 10, ראשון לציון", "custom route end address saved")
    pg.screenshot(path="/tmp/ui-settings.png", full_page=True)
    pg.click(".brand"); pg.click("text=מיילים לבדיקה")
    check("לא תואם" in pg.inner_text("main"), "needs-review email shows its problem")
    pg.click("text=יצירת הזמנה ידנית")
    check(pg.input_value("#f-name") == "רון כץ" and pg.locator("#r-p-1").count() == 1, "manual order prefilled from the email")
    pg.click(".modal button:has-text('ביטול')")
    pg.click("text=סומן כטופל"); pg.wait_for_timeout(300)
    check("אין מיילים לבדיקה" in pg.inner_text("main"), "email marked as handled")
    pg.click(".brand"); pg.click(".tile:has-text('משלוחים')")
    check(pg.locator(".stop").count() >= 3, "deliver page lists stops")
    first_before = pg.locator(".stop:not(.start) b").first.inner_text()
    pg.click("text=סידור מסלול אוטומטי"); pg.wait_for_timeout(400)
    check("נסיעה" in pg.inner_text(".route-head h2") and "דק׳ מהעצירה" in pg.inner_text(".stops"), "route shows total and per-stop drive times")
    first_after = pg.locator(".stop:not(.start) b").first.inner_text()
    check(first_before != first_after, "automatic route reorders the stops")
    check("סיום: הרצל 10, ראשון לציון" in pg.inner_text(".stops"), "route ends at the custom address")
    maps = [pg.locator(".route-head a[href*='google.com/maps/dir']").nth(k).get_attribute("href") for k in range(pg.locator(".route-head a[href*='google.com/maps/dir']").count())]
    check(len(maps) >= 1 and "waypoints=" in maps[0] and maps[-1].endswith("") and "%D7%94%D7%A8%D7%A6%D7%9C" in maps[-1], "Google Maps button opens the whole route, ending at the custom address")
    pg.locator(".stop:not(.start)").nth(1).locator("[aria-label='למעלה']").click(); pg.wait_for_timeout(200)
    check(pg.locator(".stop:not(.start) b").first.inner_text() != first_after, "a stop can be moved up")
    pg.wait_for_timeout(1800)
    check("סדר ידני" in pg.inner_text(".route-head"), "manual order recalculates times")
    pg.emulate_media(media="print"); pg.screenshot(path="/tmp/ui-print.png", full_page=True); pg.emulate_media(media="screen")
    # FIRE a packed business order (demo morning)
    pg.click(".brand"); pg.click(".big.business")
    pg.click("text=+ הזמנה חדשה"); pg.fill("#f-client-q", "ביסטרו"); pg.wait_for_timeout(150)
    pg.click(".clientpick")
    opts = pg.locator("#r-p-0 option").all_inner_texts()
    check("פילה לברק · 104" in opts and "פילה לברק טרי" not in opts, "business order offers morning products only")
    pg.select_option("#r-p-0", label="פילה לברק · 104"); pg.fill("#r-a-0", "2")
    pg.click(".modal button:has-text('יצירת הזמנה')"); pg.wait_for_timeout(400)
    check(pg.locator(".modal").count() == 0 and pg.locator(".card:has-text('ביסטרו אלנבי')").count() >= 2, "business order created with client search")
    while pg.locator(".dayhead[aria-expanded='false']").count(): pg.locator(".dayhead[aria-expanded='false']").first.click(); pg.wait_for_timeout(100)
    if pg.locator("#card-o-B1003.open").count() == 0: pg.locator("#card-o-B1003 .info").click()
    check("הוזמנו 2 יח׳ · לשקילה" in pg.inner_text("#card-o-B1003"), "business item ordered in pieces shows as pieces to weigh")
    # history above the overdue section: last 7 days by default, read only
    check(pg.locator(".day.hist").count() == 1 and pg.locator(".day.hist").evaluate("e => e.nextElementSibling && true"), "history section sits at the top of the list")
    if pg.get_attribute("[data-act='hist-toggle:business']", "aria-expanded") != "true": pg.click("[data-act='hist-toggle:business']")
    pg.wait_for_timeout(300)
    check(pg.locator("#hcard-o-B1000").count() == 1 and pg.locator(".day:not(.hist) #card-o-B1000").count() == 0, "history shows last week's order (and the main list does not)")
    pg.click("#hcard-o-B1000 .info"); pg.wait_for_timeout(200)
    check("נארז 4.125 ק״ג" in pg.inner_text("#hcard-o-B1000"), "weights show three decimals")
    pg.fill("#hf-business", "2020-01-01"); pg.fill("#ht-business", "2020-01-02"); pg.click("[data-act='hist-load:business']"); pg.wait_for_timeout(300)
    check("אין הזמנות בתאריכים האלה" in pg.inner_text(".day.hist"), "history date range can be changed")
    pg.click("[data-act='hist-toggle:business']"); pg.wait_for_timeout(200)
    fc = "#card-o-B1001"
    if pg.locator(fc + ".open").count() == 0: pg.locator(fc + " .info").click()
    for i in range(pg.locator(fc + " .winput").count()):
        inp = pg.locator(fc + " .winput").first; inp.fill("2.5"); inp.press("Enter"); pg.wait_for_timeout(150)
    pg.locator(fc + " .packbox").click(); pg.wait_for_timeout(300)
    check(pg.locator(fc + " .firemini").count() == 1, "packed business order shows FIRE without opening it")
    pg.locator(fc + " .firemini").click()
    pg.click(".modal [data-act='m-fire']"); pg.wait_for_timeout(400)
    check("הופקה" in pg.inner_text(fc), "FIRE creates the delivery note and locks the order")
    # B-1002 (ביסטרו אלנבי) has no saved price for the ponzu sauce: the regular morning price (₪18) is used
    if pg.locator("#card-o-B1002.open").count() == 0: pg.locator("#card-o-B1002 .info").click()
    pg.wait_for_timeout(200)
    check("אין מחיר שמור" not in pg.inner_text("#card-o-B1002") and "18" in pg.inner_text("#card-o-B1002"), "no client price: the item's regular price is used")
    # employee view
    pg.click("text=יציאה"); pg.fill("#lu", "basta"); pg.fill("#lp", "1234"); pg.click("button[type=submit]")
    pg.wait_for_selector(".big.private"); pg.click(".big.private")
    check(pg.locator("text=+ הזמנה חדשה").count() == 0 and pg.locator("text=פרטי הזמנה").count() == 0, "employee has no admin controls")
    pg.locator(".card").nth(1).locator(".info").click()
    check("₪" not in pg.inner_text("main"), "employee sees no prices")
    # phone, dark
    ph = b.new_page(viewport={"width": 390, "height": 844}, color_scheme="dark")
    ph.on("pageerror", lambda e: errors.append("JS error (phone): " + str(e)))
    ph.goto(BASE + "?demo"); ph.fill("#lu", "admin"); ph.fill("#lp", "9999"); ph.click("button[type=submit]")
    ph.wait_for_selector(".big.private"); ph.click(".big.private"); ph.locator(".card").nth(1).locator(".info").click()
    check(ph.evaluate("document.documentElement.scrollWidth") <= 390, "no sideways scroll on phone")
    ph.screenshot(path="/tmp/ui-phone.png")
    pg.screenshot(path="/tmp/ui-tablet.png", full_page=True)
    b.close()

print("\n%d problem(s)" % len(errors))
for e in errors: print(" -", e)
sys.exit(1 if errors else 0)
